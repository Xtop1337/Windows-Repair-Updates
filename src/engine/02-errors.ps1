function Format-FixList {
    param([string[]]$Fix)
    return (@($Fix | Where-Object { $_ } | Select-Object -Unique | ForEach-Object {
        if ($script:FixNames.ContainsKey($_)) { $script:FixNames[$_] } else { $_ }
    }) -join ', ')
}
