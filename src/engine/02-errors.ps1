function Get-ErrorInfo {
    param([string]$Code)
    $h = Format-HResult $Code
    if (-not $h) { return $null }
    $h = $h.ToUpper() -replace '^0X', '0x'
    if ($script:ErrorKB.ContainsKey($h)) {
        $e = $script:ErrorKB[$h]
        return [pscustomobject]@{ Code = $h; Text = $e.T; Fix = @($e.F); Known = $true }
    }
    # грубая классификация незнакомых кодов по «семейству»
    $text = 'Неизвестный код ошибки.'
    $fix = @('ResetWU')
    if ($h -like '0x8024*') { $text = 'Ошибка агента Центра обновления.'; $fix = @('ResetWU', 'Services', 'Policies') }
    elseif ($h -like '0x80072*') { $text = 'Сетевая ошибка.'; $fix = @('Hosts', 'Proxy', 'Firewall', 'Routes', 'Network', 'Time') }
    elseif ($h -like '0x800F*') { $text = 'Ошибка обслуживания компонентов Windows.'; $fix = @('DISM', 'ResetWU') }
    elseif ($h -like '0x80073*') { $text = 'Ошибка установки приложения (AppX/MSIX).'; $fix = @('Services', 'Sideload', 'Appx') }
    elseif ($h -like '0xC19*') { $text = 'Ошибка программы установки Windows (обновление поверх).'; $fix = @('InPlace') }
    return [pscustomobject]@{ Code = $h; Text = $text; Fix = $fix; Known = $false }
}

